class Command(BaseCommand):
    help = '生成演示数据（内容来源：西南科技大学2026级新生超全指南）'

    def handle(self, *args, **options):
        self.stdout.write('Clearing old data...')
        Feedback.objects.all().delete()
        SearchLog.objects.all().delete()
        UnansweredQuestion.objects.all().delete()
        KnowledgeItem.objects.all().delete()
        Category.objects.all().delete()

        from django.db import connection
        if connection.vendor == 'sqlite':
            cursor = connection.cursor()
            for table in ['knowledge_category', 'knowledge_knowledgeitem',
                          'knowledge_searchlog', 'knowledge_feedback',
                          'knowledge_unansweredquestion']:
                cursor.execute(f"DELETE FROM sqlite_sequence WHERE name='{table}'")

        self.stdout.write('Creating categories...')
        cats = create_categories()

        self.stdout.write('Creating knowledge items...')
        items = create_knowledge_items(cats)

        self.stdout.write('Creating search logs...')
        create_search_logs()

        self.stdout.write('Creating feedback...')
        create_feedbacks(items)

        self.stdout.write('Creating unanswered questions...')
        create_unanswered_questions()

        self.stdout.write(self.style.SUCCESS('Done!'))
        self.stdout.write(f'  Categories: {Category.objects.count()}')
        self.stdout.write(f'  Items: {KnowledgeItem.objects.count()}')
        self.stdout.write(f'  SearchLogs: {SearchLog.objects.count()}')
        self.stdout.write(f'  Feedbacks: {Feedback.objects.count()}')
        self.stdout.write(f'  Unanswered: {UnansweredQuestion.objects.count()}')
        self.stdout.write('  Run: python manage.py createsuperuser')
